-- Slice 1 — profiles row created by trigger on auth.users insert.
-- Accounts are created manually (no signup flow); full_name comes from
-- raw_user_meta_data when provided. Role defaults to 'staff' — promote to
-- 'admin' by updating the row directly.

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', new.email),
    coalesce((new.raw_user_meta_data ->> 'role')::public.user_role, 'staff')
  );
  return new;
end;
$$;

create trigger trg_on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
